"""
Convert stereo_calibration.json to Kalibr or ScaRF-SLAM configuration.

kalibr: write a Kalibr camchain file, the --cam input of
kalibr_calibrate_imu_camera.
scarf: replace the fisheye_cam0 and fisheye_cam1 blocks of a ScaRF-SLAM
config. The other keys of the template do not change, but comments are lost.
"""

import argparse
from pathlib import Path
import sys

from livekit_scarf_slam.stereo_calibration import kalibr_camchain_text
from livekit_scarf_slam.stereo_calibration import load_stereo_calibration
from livekit_scarf_slam.stereo_calibration import scarf_camera_blocks
import yaml

_SCARF_HEADER = (
    '# Camera blocks generated by convert_stereo_calibration.py from {source}.\n'
    '# To change them, run the script again. Do not edit them by hand.\n'
)


def main():
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    subparsers = parser.add_subparsers(dest='format', required=True)

    kalibr = subparsers.add_parser('kalibr', help='write a Kalibr camchain file')
    kalibr.add_argument('calibration', type=Path, help='path to stereo_calibration.json')
    kalibr.add_argument('output', type=Path, help='path of the camchain YAML to write')
    kalibr.add_argument('--cam0-topic', default='/insta/cam0/image_raw/compressed')
    kalibr.add_argument('--cam1-topic', default='/insta/cam1/image_raw/compressed')

    scarf = subparsers.add_parser('scarf', help='update the camera blocks of a ScaRF-SLAM config')
    scarf.add_argument('calibration', type=Path, help='path to stereo_calibration.json')
    scarf.add_argument('template', type=Path, help='ScaRF-SLAM config to read')
    scarf.add_argument(
        'output', type=Path, nargs='?', help='config to write (default: the template)')

    args = parser.parse_args()
    try:
        calibration = load_stereo_calibration(args.calibration)
    except (KeyError, ValueError) as error:
        sys.exit(f'error: {args.calibration}: {error}')

    if args.format == 'kalibr':
        output = args.output
        output.write_text(
            kalibr_camchain_text(calibration, args.cam0_topic, args.cam1_topic),
            encoding='utf-8')
    else:
        output = args.output or args.template
        config = yaml.safe_load(args.template.read_text(encoding='utf-8'))
        config.update(scarf_camera_blocks(calibration))
        output.write_text(
            _SCARF_HEADER.format(source=args.calibration.name)
            + yaml.safe_dump(config, sort_keys=False, default_flow_style=None, width=100),
            encoding='utf-8')
    print(f'wrote {output}')


if __name__ == '__main__':
    main()
